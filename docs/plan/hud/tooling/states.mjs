// Title + paused screenshots (pause sheet now carries camera/touch pad/sound).
// usage: node docs/plan/hud/tooling/states.mjs <url> <label> <outdir>  (env PW_CORE, CHROME as harness.mjs)
const { chromium } = await import(process.env.PW_CORE || 'playwright-core')
const [url, label, outdir] = process.argv.slice(2)
const sleep = (ms) => new Promise(r => setTimeout(r, ms))
const b = await chromium.launch({ executablePath: process.env.CHROME || '/usr/bin/google-chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, serviceWorkers: 'block' })
const page = await ctx.newPage(); const errs = []; page.on('pageerror', e => errs.push(e.message))
await page.goto(url, { waitUntil: 'load' })
await page.waitForFunction(() => document.querySelector('.garden-canvas--ready'), null, { timeout: 90000 }); await sleep(1200)
await page.screenshot({ path: `${outdir}/${label}-title-p390.png` })
await page.click('.btn--primary')
for (let i = 0; i < 10; i++) { await sleep(300); const bb = await page.$('.prologue-begin'); if (!bb) break; await bb.click() }
await page.waitForFunction(() => document.querySelector('.hud-top'), null, { timeout: 30000 })
await sleep(500)
await page.click('[aria-label="Pause"]')
await sleep(900)
await page.screenshot({ path: `${outdir}/${label}-paused-p390.png` })
const taps = await page.evaluate(() => [...document.querySelectorAll('.sheet button, .icon-btn')].map(e => { const r = e.getBoundingClientRect(); return `${(e.getAttribute('aria-label') || e.textContent).trim().slice(0, 18)} ${Math.round(r.width)}x${Math.round(r.height)}` }))
console.log(label, 'errs', errs.length, taps.join(' | '))
await b.close()
