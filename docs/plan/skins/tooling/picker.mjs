import { chromium } from 'playwright-core'
const OUT = process.env.OUT || '/workspace/snake-audit/snake-look/skins'
const sleep = (ms) => new Promise(r => setTimeout(r, ms))
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader'] })
const ctx = await b.newContext({ viewport: { width: 1280, height: 800 }, deviceScaleFactor: 1.5, serviceWorkers: 'block' })
const page = await ctx.newPage(); const errs = []; page.on('pageerror', e => errs.push(e.message))
await page.addInitScript(() => { globalThis.__serpentNoBlink = true })
await page.goto('http://localhost:4317/?perf', { waitUntil: 'load' })
await page.waitForFunction(() => document.querySelector('.garden-canvas--ready'), null, { timeout: 30000 })
await sleep(1500)
// open the Garden sheet from the title screen
await page.locator('button', { hasText: /garden|vườn/i }).first().click()
await page.waitForSelector('.garden__skins'); await sleep(800)
const sec = page.locator('.garden__skins')
await sec.scrollIntoViewIfNeeded(); await sleep(400)
console.log('before', await page.evaluate(() => ({ sel: JSON.parse(localStorage.getItem('ran-xinh-skin') || 'null'), rig: __perf.rig.skin })))
await page.screenshot({ path: `${OUT}/skin-picker.png` })
await page.locator('.garden__skin', { hasText: 'plushMoon' }).or(page.locator('.garden__skin').nth(1)).first().click()
await sleep(2500)
console.log('after', await page.evaluate(() => ({ sel: JSON.parse(localStorage.getItem('ran-xinh-skin') || 'null'), rig: __perf.rig.skin, checked: [...document.querySelectorAll('.garden__skin')].map(e => e.getAttribute('aria-checked')) })))
await page.screenshot({ path: `${OUT}/skin-picker-after-swap.png` })
await page.reload({ waitUntil: 'load' }); await page.waitForFunction(() => window.__perf?.rig, null, { timeout: 30000 }); await sleep(1000)
console.log('after reload', await page.evaluate(() => __perf.rig.skin))
console.log('errors', errs)
await b.close()
